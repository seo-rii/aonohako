func TestPicatCompileChecksEverySourceAndPublishesSubmittedFilesOnly(t *testing.T) {
	root := t.TempDir()
	sources := []model.Source{{Name: "data.txt"}, {Name: "helper.pi"}, {Name: "Main.pi"}}
	for _, source := range sources {
		if err := os.WriteFile(filepath.Join(root, source.Name), []byte(source.Name), 0o444); err != nil {
			t.Fatal(err)
		}
	}
	runner := &recordingCommandRunner{result: CommandResult{Status: model.CompileStatusOK}, hook: func(workDir, _ string, args, _ []string) {
		// The trusted helper is separate from each submitted source, and Picat
		// emits temporary bytecode beside it without running user main/0.
		if args[0] != picatCompileHelper {
			t.Fatalf("untrusted compile entrypoint: %v", args)
		}
		path := strings.TrimSuffix(args[1], ".pi") + ".qi"
		if err := os.WriteFile(path, []byte("generated bytecode"), 0o600); err != nil {
			t.Fatal(err)
		}
	}}
	resp := (picatCompiler{}).Compile(context.Background(), CompileJob{WorkDir: root, Request: &model.CompileRequest{Sources: sources}, Runner: runner})
	if resp.Status != model.CompileStatusOK || len(resp.Artifacts) != len(sources) {
		t.Fatalf("response = %+v", resp)
	}
	if len(runner.commands) != 2 {
		t.Fatalf("commands = %+v", runner.commands)
	}
	for i, name := range []string{"Main.pi", "helper.pi"} {
		command := runner.commands[i]
		if command.bin != "picat" || !reflect.DeepEqual(command.args, []string{picatCompileHelper, filepath.Join(root, name)}) || !reflect.DeepEqual(command.env, []string{"PICATPATH="}) {
			t.Fatalf("command = %+v", command)
		}
	}
	if resp.Artifacts[0].Name != "Main.pi" {
		t.Fatalf("entry artifact = %+v", resp.Artifacts[0])
	}
	for _, artifact := range resp.Artifacts {
		if artifact.DataB64 != util.EncodeB64([]byte(artifact.Name)) || artifact.Mode != "" || strings.HasSuffix(artifact.Name, ".qi") {
			t.Fatalf("published generated or modified artifact: %+v", artifact)
		}
	}
}

func TestPicatCompileRejectsBytecodeAndPreservesSyntaxFailure(t *testing.T) {
	for _, tc := range []struct {
		name, source, extra, status, reason string
		result                              CommandResult
	}{
		{name: "missing source", source: "data.txt", status: model.CompileStatusInvalid, reason: "no Picat sources"},
		{name: "bytecode shadow", source: "Main.pi", extra: "Main.qi", status: model.CompileStatusInvalid, reason: "Picat bytecode must not be submitted"},
		{name: "case folded bytecode", source: "Main.pi", extra: "helper.QI", status: model.CompileStatusInvalid, reason: "Picat bytecode must not be submitted"},
		{name: "syntax error", source: "Broken.pi", status: model.CompileStatusCompileError, reason: "bad syntax", result: CommandResult{Status: model.CompileStatusCompileError, Reason: "bad syntax", Stderr: "syntax_error"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			runner := &recordingCommandRunner{result: tc.result}
			sources := []model.Source{{Name: tc.source}}
			if tc.extra != "" {
				sources = append(sources, model.Source{Name: tc.extra})
			}
			resp := (picatCompiler{}).Compile(context.Background(), CompileJob{WorkDir: t.TempDir(), Request: &model.CompileRequest{Sources: sources}, Runner: runner})
			if resp.Status != tc.status || resp.Reason != tc.reason || resp.Stderr != tc.result.Stderr || len(resp.Artifacts) != 0 {
				t.Fatalf("response = %+v", resp)
			}
			if tc.status == model.CompileStatusInvalid && len(runner.commands) != 0 {
				t.Fatalf("invalid sources executed compiler: %+v", runner.commands)
			}
		})
	}
	if resp := (picatCompiler{}).Compile(context.Background(), CompileJob{}); resp.Status != model.CompileStatusInvalid {
		t.Fatalf("nil request = %+v", resp)
	}
}

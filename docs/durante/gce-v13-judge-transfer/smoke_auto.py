"""Send ordinary submissions through a v13 controller and worker in an offline test container."""
import argparse
from contextlib import ExitStack
import importlib.util
import json
from pathlib import Path
import sys

from protocol import digest, read, require
from verify import HERE, candidate_environment, check_automatic_routing, verify


def run(payload, output):
    registration = read(HERE / "registration.json")
    result, clock = verify(HERE / "evidence", registration)
    env = candidate_environment(result, clock)
    scope = json.loads(env["AONOHAKO_DURANTE_JUDGE_CASES"])["cases"]
    plan = registration["plan"]["arms"]["v13"]
    image = env["AONOHAKO_DURANTE_RUNTIME_IMAGE"]
    require(image == plan["image"] and len(scope) == 3, "unqualified runtime or scope")
    runtime = Path("/opt/durante")
    for name, expected in plan["files"].items():
        require(digest((runtime / name).read_bytes()) == expected, "different runtime file " + name)

    pilot = payload / "pilot"
    for name in ("guest.py", "v12_guest.py", "scripts/verify_durante_observation.py",
                 "scripts/verify_durante_native_boundaries.py", "corpus/manifest.json"):
        require(digest((pilot / name).read_bytes()) == registration["payload"]["pilot/" + name],
                "different pilot input " + name)
    sys.path.insert(0, str(pilot))
    spec = importlib.util.spec_from_file_location("qualified_pilot_guest", pilot / "guest.py")
    guest = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(guest)
    from verify_durante_observation import server

    manifest = read(pilot / "corpus/manifest.json")
    args = argparse.Namespace(server=str(runtime / "server"), runtime_image=image, latency_bound=False)
    trials = []
    with ExitStack() as processes:
        worker = processes.enter_context(server(args, 18411, False, operator_env=env, umask=0o022))
        public = processes.enter_context(server(args, 18412, False, worker,
                                          operator_env={**env, "AONOHAKO_DURANTE_JUDGE_AUTO": "on"}))
        for entry in scope:
            problem = entry["problem_id"]
            files = pilot / "corpus"
            stdin = (files / (problem + ".stdin")).read_bytes()
            expected = (files / (problem + ".stdout")).read_bytes()
            require(digest(stdin) == entry["stdin_sha256"] and digest(expected) == manifest[problem]["stdout_sha256"],
                    "different input or independent oracle")
            for role, status in (("fast", "Accepted"), ("wrong", "Wrong Answer"),
                                 ("slow", "Time Limit Exceeded"), ("unregistered", "Accepted")):
                solver = "fast" if role == "unregistered" else role
                binary = (files / (problem + "-" + solver)).read_bytes()
                require(digest(binary) == manifest[problem]["elf_sha256"][solver], "different contestant ELF")
                req = guest.request_for(problem, "native", entry["time_ms"], stdin, expected, binary, None)
                if role == "unregistered":
                    req["problem_id"] = "unregistered/" + problem
                require(not any(k.startswith("work_measurement") for k in req), "request selected its own clock")
                receipt, stdout = guest.post(public, "/execute", req)
                require(receipt["status"] == status, f"{problem}/{role} returned {receipt['status']}")
                guest.validate(receipt, "native" if role == "unregistered" else "judge",
                               req, stdout.encode(), expected, clock)
                if role == "slow":
                    require(receipt["work_measurement_execution"]["termination_source"] == "durante_work_clock",
                            "the running clock did not stop the slow submission")
                trials.append(dict(problem=problem, role=role, request_sha256=digest(json.dumps(req).encode()),
                                   receipt=receipt, stdout=stdout))

    document = dict(schema=1, image=image, model_binding=plan["binding"], worker_sha256=plan["files"]["server"],
                    env_sha256=digest(json.dumps(env, sort_keys=True).encode()), trials=trials)
    check_automatic_routing(document, HERE/"evidence", registration, clock, env)
    with output.open("x") as dest:
        json.dump(document, dest, indent=2)
        dest.write("\n")
    print(f"{len(trials)} ordinary HTTP requests passed")


if __name__ == "__main__":
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--payload", required=True, type=Path, help="directory generated by prepare.py")
    cli.add_argument("--output", required=True, type=Path, help="new JSON receipt file")
    args = cli.parse_args()
    run(args.payload.resolve(), args.output)
